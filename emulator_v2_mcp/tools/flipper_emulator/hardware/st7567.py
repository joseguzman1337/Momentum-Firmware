class ST7567Display:
    def __init__(self):
        self.width = SCREEN_WIDTH
        self.height = SCREEN_HEIGHT
        self.buffer = bytearray(SCREEN_BUFFER_SIZE)
        self.display_on = True
        self.inverted = False
        self.contrast = 32
        self.render_count = 0
        self._init_default_gui()

    def clear(self, color: int = 0):
        val = 0xFF if color else 0x00
        for i in range(len(self.buffer)):
            self.buffer[i] = val

    def set_pixel(self, x: int, y: int, value: int = 1):
        if 0 <= x < self.width and 0 <= y < self.height:
            page = y // 8
            bit = y % 8
            idx = page * self.width + x
            if value:
                self.buffer[idx] |= (1 << bit)
            else:
                self.buffer[idx] &= ~(1 << bit)

    def get_pixel(self, x: int, y: int) -> int:
        if 0 <= x < self.width and 0 <= y < self.height:
            page = y // 8
            bit = y % 8
            idx = page * self.width + x
            return (self.buffer[idx] >> bit) & 1
        return 0

    def draw_text(self, x: int, y: int, text: str, color: int = 1):
        cur_x = x
        for char in text:
            bitmap = FONT_5X7.get(char, FONT_5X7['?'])
            for col_idx, col_byte in enumerate(bitmap):
                for row_idx in range(8):
                    if (col_byte >> row_idx) & 1:
                        self.set_pixel(cur_x + col_idx, y + row_idx, color)
                    else:
                        if color == 0:
                            self.set_pixel(cur_x + col_idx, y + row_idx, 1)
            cur_x += 6

    def draw_line(self, x0: int, y0: int, x1: int, y1: int, color: int = 1):
        dx = abs(x1 - x0)
        dy = abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx - dy
        while True:
            self.set_pixel(x0, y0, color)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 > -dy:
                err -= dy
                x0 += sx
            if e2 < dx:
                err += dx
                y0 += sy

    def draw_rect(self, x: int, y: int, w: int, h: int, color: int = 1, fill: bool = False):
        if fill:
            for cy in range(y, y + h):
                for cx in range(x, x + w):
                    self.set_pixel(cx, cy, color)
        else:
            self.draw_line(x, y, x + w - 1, y, color)
            self.draw_line(x, y + h - 1, x + w - 1, y + h - 1, color)
            self.draw_line(x, y, x, y + h - 1, color)
            self.draw_line(x + w - 1, y, x + w - 1, y + h - 1, color)

    def _init_default_gui(self):
        self.clear(0)
        self.draw_rect(0, 0, 128, 10, color=1, fill=True)
        self.draw_text(2, 1, "emulator-v2", color=0)
        self.draw_text(60, 1, "BLE", color=0)
        self.draw_text(92, 1, "98%", color=0)
        
        self.draw_rect(10, 18, 48, 38, color=1, fill=False)
        self.draw_text(16, 26, "( ^_^ )", color=1)
        self.draw_text(14, 38, "Lv.3 Happy", color=1)
        
        self.draw_text(68, 16, "> Sub-GHz", color=1)
        self.draw_text(70, 26, "  125kHz RFID", color=1)
        self.draw_text(70, 36, "  NFC", color=1)
        self.draw_text(70, 46, "  Infrared", color=1)
        self.draw_text(70, 56, "  iButton", color=1)

    def render_ascii(self) -> str:
        lines = []
        lines.append("+" + "-" * 128 + "+")
        for y in range(0, self.height, 2):
            row_chars = []
            for x in range(self.width):
                top = self.get_pixel(x, y)
                bottom = self.get_pixel(x, y + 1)
                if top and bottom: row_chars.append("█")
                elif top and not bottom: row_chars.append("▀")
                elif not top and bottom: row_chars.append("▄")
                else: row_chars.append(" ")
            lines.append("|" + "".join(row_chars) + "|")
        lines.append("+" + "-" * 128 + "+")
        return "\n".join(lines)

    def to_pbm(self) -> bytes:
        header = f"P4\n{self.width} {self.height}\n".encode("ascii")
        pbm_data = bytearray(self.width * self.height // 8)
        byte_idx = 0
        for y in range(self.height):
            for x_byte in range(self.width // 8):
                b = 0
                for bit in range(8):
                    x = x_byte * 8 + bit
                    if self.get_pixel(x, y):
                        b |= (1 << (7 - bit))
                pbm_data[byte_idx] = b
                byte_idx += 1
        return header + pbm_data

    def to_base64_pbm(self) -> str:
        return base64.b64encode(self.to_pbm()).decode("ascii")

    def get_framebuffer(self) -> bytes:
        return bytes(self.buffer)

    def set_framebuffer(self, data: bytes):
        if len(data) == SCREEN_BUFFER_SIZE:
            self.buffer[:] = data
            self.render_count += 1
